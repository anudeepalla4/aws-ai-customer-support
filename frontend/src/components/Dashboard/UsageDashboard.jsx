import { useEffect, useMemo, useState } from "react";
import {
  Activity,
  ArrowDownToLine,
  ArrowUpFromLine,
  BarChart3,
  CircleDollarSign,
  Cpu,
  RefreshCw,
  Sparkles,
  Zap,
} from "lucide-react";
import { getUsageDashboard } from "../../services/analyticsService";

const numberFormat = new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 });
const currencyFormat = new Intl.NumberFormat("en-US", {
  style: "currency",
  currency: "USD",
  minimumFractionDigits: 4,
  maximumFractionDigits: 6,
});

function formatNumber(value = 0) {
  return numberFormat.format(Number(value) || 0);
}

function formatCost(value = 0) {
  return currencyFormat.format(Number(value) || 0);
}

function MetricCard({ icon: Icon, label, value, detail, tone }) {
  return (
    <article className={`metric-card metric-${tone}`}>
      <div className="metric-topline">
        <span className="metric-label">{label}</span>
        <span className="metric-icon"><Icon size={17} /></span>
      </div>
      <div className="metric-value">{value}</div>
      <div className="metric-detail">{detail}</div>
    </article>
  );
}

export default function UsageDashboard({ onBack }) {
  const [period, setPeriod] = useState("30d");
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState("");

  async function loadDashboard(selectedPeriod = period, isRefresh = false, signal) {
    if (isRefresh) setRefreshing(true);
    else setLoading(true);
    setError("");
    try {
      const result = await getUsageDashboard(selectedPeriod, signal);
      setData(result);
    } catch (err) {
      if (err.name !== "AbortError") setError(err.message || "Unable to load usage analytics.");
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  }

  useEffect(() => {
    const controller = new AbortController();
    loadDashboard(period, false, controller.signal);
    return () => controller.abort();
    // period is the only dependency; loadDashboard intentionally uses the selected period.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [period]);

  const summary = data?.summary || {};
  const models = data?.modelBreakdown || [];
  const trend = data?.dailyTrend || [];
  const maxDailyCost = useMemo(
    () => Math.max(0, ...trend.map((day) => Number(day.totalCost) || 0)),
    [trend]
  );
  const maxModelCost = Math.max(0, ...models.map((model) => Number(model.totalCost) || 0));

  return (
    <main className="dashboard-main">
      <header className="dashboard-header">
        <div className="dashboard-heading">
          <div className="dashboard-eyebrow"><Activity size={13} /> BEDROCK OBSERVABILITY</div>
          <h1>Model usage &amp; cost</h1>
          <p>Track token consumption and estimated model spend across your Bedrock integrations.</p>
        </div>
        <div className="dashboard-actions">
          <button className="dashboard-back" onClick={onBack}>Back to chat</button>
          <button className="refresh-button" onClick={() => loadDashboard(period, true)} disabled={loading || refreshing}>
            <RefreshCw size={14} className={refreshing ? "refresh-spin" : ""} /> Refresh
          </button>
        </div>
      </header>

      <div className="dashboard-toolbar">
        <div className="dashboard-period-label">Usage period</div>
        <div className="period-switch" role="group" aria-label="Usage period">
          {[{ value: "7d", label: "7 days" }, { value: "30d", label: "30 days" }, { value: "90d", label: "90 days" }, { value: "all", label: "All time" }].map((item) => (
            <button key={item.value} className={period === item.value ? "selected" : ""} onClick={() => setPeriod(item.value)}>{item.label}</button>
          ))}
        </div>
      </div>

      {error && <div className="dashboard-error">{error}<button onClick={() => loadDashboard(period, true)}>Try again</button></div>}

      {loading && !data ? (
        <div className="dashboard-loading"><span className="loading-orb"><Sparkles size={20} /></span><span>Loading usage analytics…</span></div>
      ) : (
        <>
          <section className="metrics-grid">
            <MetricCard icon={CircleDollarSign} label="Total model cost" value={formatCost(summary.totalCost)} detail={`${formatNumber(summary.totalRequests)} model requests · USD`} tone="cost" />
            <MetricCard icon={ArrowDownToLine} label="Input tokens" value={formatNumber(summary.inputTokens)} detail="Tokens sent to models" tone="input" />
            <MetricCard icon={ArrowUpFromLine} label="Output tokens" value={formatNumber(summary.outputTokens)} detail="Tokens generated by models" tone="output" />
            <MetricCard icon={Zap} label="Total tokens" value={formatNumber(summary.totalTokens)} detail={`${formatNumber(summary.modelsUsed)} models used`} tone="total" />
          </section>

          <section className="dashboard-panel model-panel">
            <div className="panel-heading">
              <div><h2>Model-wise usage</h2><p>Token consumption and cost for each model or inference profile.</p></div>
              <span className="panel-count"><Cpu size={13} /> {models.length} models</span>
            </div>
            {models.length === 0 ? (
              <div className="empty-analytics"><BarChart3 size={25} /><strong>No usage recorded yet</strong><span>Send a chat message after integrating the backend usage recorder. New Bedrock calls will appear here.</span></div>
            ) : (
              <div className="model-table-wrap">
                <table className="model-table">
                  <thead><tr><th>Model</th><th>Input tokens</th><th>Output tokens</th><th>Total tokens</th><th>Requests</th><th className="align-right">Total cost (USD)</th></tr></thead>
                  <tbody>
                    {models.map((model) => (
                      <tr key={model.modelId}>
                        <td><div className="model-name-cell"><span className="model-symbol"><Cpu size={15} /></span><div><strong>{model.modelName}</strong><small title={model.modelId}>{model.modelId}</small></div></div></td>
                        <td>{formatNumber(model.inputTokens)}</td>
                        <td>{formatNumber(model.outputTokens)}</td>
                        <td className="numeric-strong">{formatNumber(model.totalTokens)}</td>
                        <td>{formatNumber(model.totalRequests)}</td>
                        <td className="align-right cost-cell">{formatCost(model.totalCost)}
                          <div className="cost-track"><span style={{ width: `${maxModelCost ? Math.max(2, (Number(model.totalCost) / maxModelCost) * 100) : 0}%` }} /></div>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
            {summary.totalRequests > 0 && summary.costCoveragePercent < 100 && (
              <div className="coverage-note">Cost calculated for {summary.costCoveragePercent}% of recorded requests. Add configured pricing for any models with missing cost values.</div>
            )}
          </section>

          <section className="dashboard-panel trend-panel">
            <div className="panel-heading"><div><h2>Daily cost trend</h2><p>Daily spend across all models in the selected period.</p></div><span className="trend-unit">USD / day</span></div>
            {trend.length === 0 ? <div className="empty-trend">Daily usage will appear after the first recorded model request.</div> : (
              <div className="trend-list">
                {trend.slice(-14).map((day) => (
                  <div className="trend-row" key={day.date}>
                    <span className="trend-date">{new Date(`${day.date}T00:00:00Z`).toLocaleDateString("en-US", { month: "short", day: "numeric", timeZone: "UTC" })}</span>
                    <div className="trend-track"><span style={{ width: `${maxDailyCost ? Math.max(1, (Number(day.totalCost) / maxDailyCost) * 100) : 0}%` }} /></div>
                    <strong>{formatCost(day.totalCost)}</strong>
                  </div>
                ))}
              </div>
            )}
          </section>
          <div className="dashboard-footnote"><span className="status-dot" /> Data is read from MongoDB usage records. Costs are only as accurate as the model-specific rates configured in your backend.</div>
        </>
      )}
    </main>
  );
}
